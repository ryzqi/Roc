import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(fileURLToPath(import.meta.url), '..', '..');
const schemaPath = resolve(repoRoot, 'src/shared/ipc-schema.json');
const generatedPath = resolve(repoRoot, 'src/shared/ipc-generated.ts');
const checkOnly = process.argv.includes('--check');

function readSchema() {
  const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));
  validateSchema(schema);
  return schema;
}

function validateSchema(schema) {
  if (typeof schema.version !== 'number') {
    throw new Error('IPC schema version must be a number.');
  }
  for (const section of ['requests', 'events']) {
    if (!Array.isArray(schema[section])) {
      throw new Error(`IPC schema ${section} must be an array.`);
    }
  }
  const keys = new Set();
  const channels = new Set();
  for (const entry of [...schema.requests, ...schema.events]) {
    if (typeof entry.key !== 'string' || entry.key.length === 0) {
      throw new Error('IPC schema entry key must be a non-empty string.');
    }
    if (typeof entry.channel !== 'string' || !entry.channel.startsWith('roc:')) {
      throw new Error(`IPC schema entry ${entry.key} has an invalid channel.`);
    }
    if (keys.has(entry.key)) {
      throw new Error(`Duplicate IPC schema key: ${entry.key}`);
    }
    if (channels.has(entry.channel)) {
      throw new Error(`Duplicate IPC channel: ${entry.channel}`);
    }
    keys.add(entry.key);
    channels.add(entry.channel);
  }
}

function formatArray(name, entries) {
  const body = entries.map((entry) => `  '${entry.key}'`).join(',\n');
  return `export const ${name} = [\n${body}\n] as const;`;
}

function generate(schema) {
  const allEntries = [...schema.requests, ...schema.events];
  const channels = allEntries.map((entry) => `  ${entry.key}: '${entry.channel}'`).join(',\n');
  return `// This file is generated by scripts/generate-ipc-schema.mjs. Do not edit manually.\n\nexport const ipcSchemaVersion = ${schema.version} as const;\n\nexport const ipcChannels = {\n${channels}\n} as const;\n\n${formatArray('ipcRequestChannelKeys', schema.requests)}\n\n${formatArray('ipcEventChannelKeys', schema.events)}\n\nexport type IpcChannelKey = keyof typeof ipcChannels;\nexport type IpcRequestChannelKey = (typeof ipcRequestChannelKeys)[number];\nexport type IpcEventChannelKey = (typeof ipcEventChannelKeys)[number];\n`;
}

const generated = generate(readSchema());

if (checkOnly) {
  const current = readFileSync(generatedPath, 'utf8');
  if (current !== generated) {
    throw new Error('IPC generated files are out of date. Run pnpm generate:ipc.');
  }
  console.log('IPC generated files are current.');
} else {
  writeFileSync(generatedPath, generated, 'utf8');
  console.log(`Generated ${generatedPath}`);
}
