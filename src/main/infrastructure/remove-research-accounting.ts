import type {Database} from 'better-sqlite3';
import {executionPayloadHash} from './execution-events';

type JsonObject = Record<string, unknown>;
function object(value: unknown): JsonObject {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) throw new Error('research_migration_object_invalid');
  return value as JsonObject;
}
/** Only known structured execution metadata is rewritten; user prose is retained. */
function clean(value: unknown): void {
  if (Array.isArray(value)) {value.forEach(clean); return;}
  if (value === null || typeof value !== 'object') return;
  const record = value as JsonObject;
  if (record.searchPlan !== undefined) {
    const plan = object(record.searchPlan);
    const previous = JSON.stringify(plan, null, 2);
    delete plan.budget;
    if (Array.isArray(plan.queries)) for (const query of plan.queries) delete object(query).maxRequests;
    // This exact JSON suffix is generated by searchPlanReviewMarkdown.
    const suffix = `\n\n\`\`\`json\n${previous}\n\`\`\``;
    if (typeof record.markdown === 'string' && record.markdown.endsWith(suffix)) {
      record.markdown = record.markdown.slice(0, -suffix.length) + `\n\n\`\`\`json\n${JSON.stringify(plan, null, 2)}\n\`\`\``;
    }
  }
  Object.values(record).forEach(clean);
}
function contextHash(context: JsonObject): string {
  return executionPayloadHash({project: context.project, skillInstructions: context.skillInstructions,
    skillPin: context.skillPin, inputs: context.inputs,
    ...(context.scientificInput === undefined ? {} : {scientificInput: context.scientificInput})});
}
export function removeResearchAccounting(db: Database): void {
  for (const row of db.prepare('SELECT artifact_id, output_json FROM research_artifact_contents').all() as Array<{artifact_id:string;output_json:string}>) {
    const output = JSON.parse(row.output_json);
    clean(output);
    db.prepare('UPDATE research_artifact_contents SET output_json=? WHERE artifact_id=?').run(JSON.stringify(output),row.artifact_id);
  }
  for (const [table, key, column] of [
    ['research_literature_searches', 'id', 'result_json'],
    ['research_literature_search_executions', 'id', 'request_json'],
    ['research_literature_search_pools', 'execution_id', 'pool_json']
  ]) {
    for (const row of db.prepare(`SELECT ${key} id, ${column} json FROM ${table}`).all() as Array<{id:string;json:string}>) {
      const value = object(JSON.parse(row.json));
      if (value.strategy === null || value.strategy === undefined || !('maxRequests' in object(value.strategy))) continue;
      if (table === 'research_literature_search_pools') {
        const {contentHash, ...body} = value;
        if (contentHash !== executionPayloadHash(body)) throw new Error('literature_pool_integrity_invalid');
      }
      delete object(value.strategy).maxRequests;
      if (table === 'research_literature_search_pools') {
        const {contentHash: _previous, ...body} = value;
        value.contentHash = executionPayloadHash(body);
      }
      db.prepare(`UPDATE ${table} SET ${column}=? WHERE ${key}=?`).run(JSON.stringify(value), row.id);
    }
  }
  for (const row of db.prepare('SELECT id, snapshot_json, context_json FROM research_stage_runs').all() as Array<{id:string;snapshot_json:string;context_json:string}>) {
    const context = object(JSON.parse(row.context_json));
    const oldHash = contextHash(context);
    clean(context);
    if (JSON.stringify(context) === row.context_json) continue;
    const run = JSON.parse(row.snapshot_json);
    const frozen = run.executionSnapshot?.frozenInputs;
    if (frozen !== undefined) {
      const before = JSON.stringify(frozen);
      const version = (frozen.versions as JsonObject[]).find((entry) => entry.kind === 'context' && entry.id === row.id);
      if (version?.hash !== oldHash) throw new Error('research_stage_snapshot_invalid');
      version.hash = contextHash(context);
      db.prepare('INSERT INTO research_execution_input_migrations(execution_id, previous_json, current_json) VALUES(?,?,?)')
        .run(row.id,before,JSON.stringify(frozen));
    }
    db.prepare('UPDATE research_stage_runs SET snapshot_json=?,context_json=? WHERE id=?').run(JSON.stringify(run),JSON.stringify(context),row.id);
  }
}
